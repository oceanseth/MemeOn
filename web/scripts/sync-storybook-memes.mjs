#!/usr/bin/env node
/**
 * Pull public meme art from dev.memeon.ai into Storybook fixtures.
 * Reads repo-root localstorage.json (memeon_session or masky_access_token).
 *
 *   node web/scripts/sync-storybook-memes.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const storagePath = path.join(root, 'localstorage.json')
const outPath = path.join(root, 'web/.storybook/dev-meme-media.ts')

function readToken() {
  if (!fs.existsSync(storagePath)) {
    throw new Error(`missing ${storagePath} — log in via agent-browser first`)
  }
  const storage = JSON.parse(fs.readFileSync(storagePath, 'utf8'))
  const token = storage.memeon_session ?? storage.masky_access_token
  if (!token) throw new Error('localstorage.json has no memeon_session or masky_access_token')
  return token
}

const ROLE_PICKERS = {
  paper: (m) => m.tierKey === 'paper' && m.mediaType === 'image',
  silver: (m) => m.tierKey === 'silver' && m.mediaType === 'image' && m.title === 'pushrax',
  holo: (m) => m.tierKey === 'holo' && m.mediaType === 'image',
  chrome: (m) => m.tierKey === 'chrome' && m.mediaType === 'image',
  gold: (m) => m.tierKey === 'gold' && m.mediaType === 'image',
  shiny: (m) => m.tierKey === 'shiny' && m.mediaType === 'image',
  listed: (m) =>
    m.listing?.shares > 0 && m.mediaType === 'image' && m.tierKey === 'silver' && m.title === 'pushrax',
  video: (m) => m.mediaType === 'video' && m.videoUrl,
}

function pickRole(memes, pred) {
  const matches = memes.filter(pred).sort((a, b) => b.reshares - a.reshares)
  return matches.find((m) => !m.imageUrl.includes('placecats.com')) ?? matches[0] ?? null
}

function slim(m) {
  return {
    id: m.id,
    title: m.title,
    imageUrl: m.imageUrl,
    videoUrl: m.videoUrl ?? null,
    reshares: m.reshares,
    tierKey: m.tierKey,
    listing: m.listing ?? null,
    creatorId: m.creatorId,
    creatorName: m.creatorName,
    ownerId: m.ownerId,
    ownerName: m.ownerName,
    mediaType: m.mediaType,
  }
}

async function main() {
  const token = readToken()
  const headers = { Authorization: `Bearer ${token}` }
  const [memeRes, frameRes] = await Promise.all([
    fetch('https://dev.memeon.ai/api/memes?limit=120', { headers }),
    fetch('https://dev.memeon.ai/api/frames'),
  ])
  const memeBody = await memeRes.json()
  if (!memeRes.ok || memeBody.error) {
    throw new Error(memeBody.error ?? `memes fetch failed (${memeRes.status})`)
  }
  const framesBody = await frameRes.json()
  const memes = memeBody.memes ?? []
  const frames = Object.fromEntries((framesBody.frames ?? []).map((f) => [f.key, f.url]))

  const roles = {}
  for (const [role, pred] of Object.entries(ROLE_PICKERS)) {
    const picked = pickRole(memes, pred)
    if (picked) roles[role] = slim(picked)
  }

  if (roles.gold) {
    roles.prismatic = {
      ...roles.gold,
      id: `${roles.gold.id}-prismatic-demo`,
      reshares: 5000,
      tierKey: 'prismatic',
      listing: null,
    }
  }

  const missing = Object.keys(ROLE_PICKERS).filter((role) => !roles[role])
  if (missing.length) throw new Error(`could not pick roles: ${missing.join(', ')}`)

  const payload = { frames, roles }
  const ts = `/** Auto-generated by web/scripts/sync-storybook-memes.mjs — do not edit by hand. */\nexport const devMemeMedia = ${JSON.stringify(payload, null, 2)} as const\n`
  fs.writeFileSync(outPath, ts)
  console.log(`wrote ${path.relative(root, outPath)} (${Object.keys(roles).join(', ')})`)
}

main().catch((err) => {
  console.error(err.message ?? err)
  process.exit(1)
})
